/** 엑셀에서 바로 열리게 UTF-8 BOM을 붙인 CSV. */
function csv(name, rows) {
  const text = rows.map((row) => row.map((cell) => (/[",\n]/.test(String(cell)) ? `"${String(cell).replace(/"/g, '""')}"` : cell)).join(",")).join("\r\n");

  writeFileSync(`${OUT}/${name}`, `﻿${text}\r\n`, "utf8");
}

